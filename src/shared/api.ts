import type { State, Patch, TimerAction, Settings, RecordFor, Prayer } from './schema';
import type { PrayerTimesMap } from './prayer';
import type { CommitImport, Format, Mapping, Preview } from './imports';
import type { PairInfo, SyncInfo } from './phone';
import type { PrayerEdit } from './prayer-record';
import type { PlannerRequest, PlanDay } from './logic/planner';
import type { LmsConnect, LmsApply, LmsPreview, LmsResult } from './logic/lms-mapping';
export interface SabriApi {
  generatePlan(input: PlannerRequest): Promise<PlanDay[]>;
  captureParking(): Promise<void>;
  quietMock(minutes:number):Promise<void>;
  connectLms(input:LmsConnect): Promise<LmsPreview>;
  syncLms(id:string): Promise<LmsPreview>;
  applyLms(input:LmsApply): Promise<LmsResult>;
  disconnectLms(id:string): Promise<void>;
  importLmsCalendar(label:string): Promise<LmsPreview|null>;
  addAttachment(input:{id:string;domain:'assignment'|'note';mode:'copied'|'linked'}):Promise<RecordFor<'assignments'>['attachments'][number]|null>;
  openAttachment(input:{id:string;domain:'assignment'|'note';file?:string;folder?:boolean}):Promise<boolean>;
  addNoteImage(input:{id:string;name:string;bytes:Uint8Array;format:'png'|'jpg'|'webp'|'gif'}):Promise<RecordFor<'notes'>['attachments'][number]>;
  exportAddonPdf(kind:'formula'|'note'):Promise<boolean>;
  openResource(id:string):Promise<void>;
  saveRecapImage(bytes:Uint8Array):Promise<boolean>;
  saveScheduleImage(data: Uint8Array): Promise<boolean>;
  checkUpdates(): Promise<{ state:'unconfigured'|'current' } | { state:'available';version:string }>;
  downloadUpdate(): Promise<boolean>;
  installUpdate(): Promise<void>;
  checkPrayer(input: PrayerEdit): Promise<State>;
  verifyPrayer(key: string): Promise<{ name:Prayer; local:string; remote:string; minutes:number }[]>;
  estimateLocation(): Promise<Settings['location']>;
  importTheme(): Promise<RecordFor<'themes'> | null>;
  exportTheme(theme: RecordFor<'themes'>): Promise<boolean>;
  addSound(): Promise<{ id:string; name:string; file:string } | null>;
  syncInfo(): Promise<SyncInfo>;
  syncStart(options: { port:number;pin?:string;secure?:boolean }): Promise<SyncInfo>;
  syncStop(): Promise<SyncInfo>;
  exportPhoneCertificate(): Promise<{ fingerprint:string } | null>;
  testPhoneAlert(): Promise<boolean>;
  syncPair(): Promise<PairInfo>;
  syncDevice(options: { id:string;name:string;canEdit:boolean }): Promise<SyncInfo>;
  syncRevoke(id: string): Promise<SyncInfo>;
  timetable(input: { format: Format; text?: string; mapping?: Mapping }): Promise<Preview | null>;
  previewFeed(url: string): Promise<Preview>;
  pendingFeeds(): Promise<string[]>;
  refreshFeed(id: string): Promise<Preview>;
  commitImport(input: CommitImport): Promise<{ saved: number; skipped: number }>;
  exportCalendar(scope: 'schedule'|'calendar'|'csv'): Promise<boolean>;
  load(): Promise<{ state: State; recoveredFrom?: string }>;
  apply(patch: Patch): Promise<State>;
  timer(action: TimerAction): Promise<State>;
  changed(listener: (state: State) => void): () => void;
  saveBackup(): Promise<boolean>;
  importBackup(): Promise<boolean>;
  backups(): Promise<string[]>;
  restoreBackup(id: string): Promise<State>;
  prayers(input: { key: string; settings: Settings }): Promise<PrayerTimesMap>;
  mini(): Promise<void>;
  onShortcut(listener: (name: string) => void): () => void;
  print(): Promise<void>;
}
declare global { interface Window { sabri: SabriApi } }
